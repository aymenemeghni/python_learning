import math

#mathematical functions 

#round()   -> round to the nearest integer
print(round(3.49))

#ceil()    -> round up to the nearest integer
print(math.ceil(3.1))

#floor()   -> round down to the nearest integer
print(math.floor(3.9))

#sqrt()    -> square root
print(math.sqrt(16))

#pow()     -> power
print(pow(2, 3))

#min()     -> minimum value
print(min(1, 2, 3, 4, 5))

#max()     -> maximum value
print(max(1, 2, 3, 4, 5))
#abs()     -> absolute value
print(abs(-10))

#pi        -> pi
print(math.pi)

print(math.e)


